//! What Akai's app sends the controller when it starts, byte for byte, from the
//! passive USB capture of Hello MPC round 2 (stock 3.6, `systemctl restart
//! acvs.service`, 2026-11-10). Round 3 sends only these bytes, plus pad colours
//! made by the same rule the app uses when a pad is hit.
//!
//! What each setup message does is not known. They are replayed exactly, in the
//! app's order, so the controller ends where it does after every factory boot.

/// Universal SysEx identity request, on Public. The controller answers on Public
/// and Private with its model and its serial number (never shown or saved).
pub const IDENTITY_REQUEST: [u8; 6] = [0xF0, 0x7E, 0x00, 0x06, 0x01, 0xF7];

/// The session token the app used in the capture. The app picks a new one at
/// every start; the controller only checks that pings keep the same one.
pub const SESSION_TOKEN: [u8; 4] = [0x15, 0x21, 0x6D, 0x43];

/// Seconds between session pings, as the app does once it is running.
pub const PING_SECONDS: u64 = 4;

/// Reply status bytes seen in the capture: 0 = the controller still holds an
/// older token (the reply carries that token), 2 = this token was just accepted,
/// 1 = this token's session is running.
pub const SESSION_HELD: u8 = 0x00;
pub const SESSION_RUNNING: u8 = 0x01;
pub const SESSION_ACCEPTED: u8 = 0x02;

/// The session ping, on Public: F0 47 00 46 52 00 04 <token> F7.
pub fn session_ping(token: [u8; 4]) -> [u8; 12] {
    [0xF0, 0x47, 0x00, 0x46, 0x52, 0x00, 0x04, token[0], token[1], token[2], token[3], 0xF7]
}

/// A session reply, from Private: F0 47 7F 46 53 00 05 <token> <status> F7.
/// Returns the token and the status byte.
pub fn session_reply(bytes: &[u8]) -> Option<([u8; 4], u8)> {
    match bytes {
        [0xF0, 0x47, 0x7F, 0x46, 0x53, 0x00, 0x05, a, b, c, d, status, 0xF7] => Some(([*a, *b, *c, *d], *status)),
        _ => None,
    }
}

/// True for the controller's identity reply, whose last bytes are its serial number.
pub fn is_identity_reply(bytes: &[u8]) -> bool {
    bytes.len() > 5 && bytes[0] == 0xF0 && bytes[1] == 0x7E && bytes[3] == 0x06 && bytes[4] == 0x02
}

/// How many leading bytes of an identity reply are shown: manufacturer, family,
/// model and version. The rest (the serial number in ASCII) is hidden.
pub const IDENTITY_SHOWN: usize = 18;

