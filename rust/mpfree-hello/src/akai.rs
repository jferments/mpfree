/// One button light message: B0 <note> <value>, for the Private port.
pub fn button_light(note: u8, value: u8) -> [u8; 3] {
    [0xB0, note & 0x7F, value & 0x7F]
}

/// One pad colour message: F0 47 7F 46 65 00 04 <pad 0-15> R G B F7, for the Public port.
pub fn pad_colour(pad: u8, rgb: [u8; 3]) -> [u8; 12] {
    [0xF0, 0x47, 0x7F, 0x46, 0x65, 0x00, 0x04, pad & 0x0F, rgb[0] & 0x7F, rgb[1] & 0x7F, rgb[2] & 0x7F, 0xF7]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn hit_colours_match_the_capture() {
        assert_eq!(hit_colour([0x3F, 0x00, 0x00]), [0x7F, 0x00, 0x00]);
        assert_eq!(hit_colour([0x3B, 0x3B, 0x09]), [0x76, 0x76, 0x12]);
        assert_eq!(hit_colour([0x3F, 0x22, 0x00]), [0x7F, 0x44, 0x00]);
        for rest in RESTING_COLOURS {
            assert!(hit_colour(rest).iter().all(|&v| v <= 0x7F));
        }
    }

    #[test]
    fn kit_colours_were_all_seen() {
        for c in KIT_COLOURS {
            assert!(RESTING_COLOURS.contains(&c), "{c:02X?}");
        }
        assert_eq!(kit_colour(7), KIT_COLOURS[0]);
    }

    #[test]
    fn messages_match_the_capture() {
        assert_eq!(session_ping(SESSION_TOKEN), [0xF0, 0x47, 0x00, 0x46, 0x52, 0x00, 0x04, 0x15, 0x21, 0x6D, 0x43, 0xF7]);
        assert_eq!(pad_colour(0, [0x3F, 0x0F, 0x00]), [0xF0, 0x47, 0x7F, 0x46, 0x65, 0x00, 0x04, 0x00, 0x3F, 0x0F, 0x00, 0xF7]);
        assert_eq!(button_light(0x35, 3), [0xB0, 0x35, 0x03]);
        let reply = [0xF0, 0x47, 0x7F, 0x46, 0x53, 0x00, 0x05, 0x15, 0x21, 0x6D, 0x43, 0x02, 0xF7];
        assert_eq!(session_reply(&reply), Some((SESSION_TOKEN, SESSION_ACCEPTED)));
        assert_eq!(session_reply(&reply[..12]), None);
        // Every setup message is one complete Akai SysEx (or the identity request).
        for m in SETUP_FIRST.iter().chain(SETUP_LAST.iter()).chain([&SETUP_5A[..]].iter()) {
            assert_eq!((m[0], *m.last().unwrap()), (0xF0, 0xF7));
            assert!(m[1..m.len() - 1].iter().all(|&b| b < 0x80));
            assert!(m[1] == 0x47 || m[1] == 0x7E);
            // Akai's length field (byte 6) matches the data that follows.
            if m[1] == 0x47 {
                assert_eq!(m[6] as usize, m.len() - 8, "{m:02X?}");
            }
        }
        assert!(STARTUP_BUTTON_LIGHTS.iter().all(|&[n, v]| n < 0x80 && (1..=4).contains(&v)));
    }

    #[test]
    fn identity_replies_are_recognised() {
        let reply = [0xF0, 0x7E, 0x00, 0x06, 0x02, 0x47, 0x46, 0x00, 0x19, 0x00, 0x00, 0x01, 0x00, 0x7F, 0x00, 0x00,
                     0x00, 0x00, 0x58, 0x58, 0x00, 0xF7]; // "XX": a made-up serial
        assert!(is_identity_reply(&reply));
        assert!(!is_identity_reply(&IDENTITY_REQUEST));
    }
}
